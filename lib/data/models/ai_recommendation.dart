/// The urgency level of an AI-generated recommendation.
enum RecommendationPriority {
  /// Requires immediate farmer action — critical condition detected.
  urgent,

  /// Situation needs attention soon but is not yet critical.
  attention,

  /// Condition is healthy — informational only.
  safe,
}

/// The thematic category of an AI-generated recommendation.
enum RecommendationCategory {
  /// Related to watering or irrigation management.
  irrigation,

  /// Related to fertilizer or nutrient management.
  fertilizer,

  /// Related to pest or disease detection and control.
  pest,

  /// Related to weather or climate conditions.
  climate,

  /// Related to harvest timing or post-harvest handling.
  harvest,
}

/// A single AI-generated recommendation based on live sensor context.
class AiRecommendation {
  /// Unique identifier for this recommendation.
  final String id;

  /// Short, human-readable title summarizing the recommendation.
  final String title;

  /// Detailed description of the detected condition.
  final String description;

  /// The specific action the farmer should take.
  final String action;

  /// The data-driven reason explaining why this action is needed.
  final String reason;

  /// Urgency level of this recommendation.
  final RecommendationPriority priority;

  /// Thematic category this recommendation belongs to.
  final RecommendationCategory category;

  /// When this recommendation was generated by the AI.
  final DateTime generatedAt;

  /// Snapshot of sensor values that triggered this recommendation.
  ///
  /// Keys are sensor names (e.g., `'soilHumidity'`, `'phLevel'`).
  final Map<String, double> sensorContext;

  /// Whether the farmer has already acted on this recommendation.
  final bool isActioned;

  const AiRecommendation({
    required this.id,
    required this.title,
    required this.description,
    required this.action,
    required this.reason,
    required this.priority,
    required this.category,
    required this.generatedAt,
    required this.sensorContext,
    this.isActioned = false,
  });

  // ──────────────────────────── copyWith ───────────────────────────────────

  AiRecommendation copyWith({
    String? id,
    String? title,
    String? description,
    String? action,
    String? reason,
    RecommendationPriority? priority,
    RecommendationCategory? category,
    DateTime? generatedAt,
    Map<String, double>? sensorContext,
    bool? isActioned,
  }) {
    return AiRecommendation(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      action: action ?? this.action,
      reason: reason ?? this.reason,
      priority: priority ?? this.priority,
      category: category ?? this.category,
      generatedAt: generatedAt ?? this.generatedAt,
      sensorContext: sensorContext ?? this.sensorContext,
      isActioned: isActioned ?? this.isActioned,
    );
  }

  // ──────────────────────────── JSON ───────────────────────────────────────

  /// Serializes this [AiRecommendation] to a JSON-compatible [Map].
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'action': action,
      'reason': reason,
      'priority': priority.name,
      'category': category.name,
      'generatedAt': generatedAt.toIso8601String(),
      'sensorContext': sensorContext,
      'isActioned': isActioned,
    };
  }

  /// Creates an [AiRecommendation] from a JSON [Map].
  factory AiRecommendation.fromJson(Map<String, dynamic> json) {
    return AiRecommendation(
      id: json['id'] as String,
      title: json['title'] as String,
      description: json['description'] as String,
      action: json['action'] as String,
      reason: json['reason'] as String,
      priority: RecommendationPriority.values.firstWhere(
        (e) => e.name == json['priority'],
        orElse: () => RecommendationPriority.safe,
      ),
      category: RecommendationCategory.values.firstWhere(
        (e) => e.name == json['category'],
        orElse: () => RecommendationCategory.irrigation,
      ),
      generatedAt: DateTime.parse(json['generatedAt'] as String),
      sensorContext: Map<String, double>.from(
        (json['sensorContext'] as Map).map(
          (k, v) => MapEntry(k as String, (v as num).toDouble()),
        ),
      ),
      isActioned: json['isActioned'] as bool? ?? false,
    );
  }

  // ─────────────────────────── Display Helpers ─────────────────────────────

  /// Returns the Bahasa Indonesia label for the priority level.
  String get priorityLabel {
    switch (priority) {
      case RecommendationPriority.urgent:
        return 'Mendesak';
      case RecommendationPriority.attention:
        return 'Perhatian';
      case RecommendationPriority.safe:
        return 'Aman';
    }
  }

  /// Returns the Bahasa Indonesia label for the category.
  String get categoryLabel {
    switch (category) {
      case RecommendationCategory.irrigation:
        return 'Irigasi';
      case RecommendationCategory.fertilizer:
        return 'Pupuk';
      case RecommendationCategory.pest:
        return 'Hama & Penyakit';
      case RecommendationCategory.climate:
        return 'Iklim';
      case RecommendationCategory.harvest:
        return 'Panen';
    }
  }

  /// Returns the emoji icon representing the category.
  String get categoryEmoji {
    switch (category) {
      case RecommendationCategory.irrigation:
        return '💧';
      case RecommendationCategory.fertilizer:
        return '🌱';
      case RecommendationCategory.pest:
        return '🐛';
      case RecommendationCategory.climate:
        return '☁️';
      case RecommendationCategory.harvest:
        return '🌾';
    }
  }

  @override
  String toString() =>
      'AiRecommendation(id: $id, title: $title, priority: ${priority.name}, '
      'category: ${category.name}, isActioned: $isActioned)';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is AiRecommendation &&
          runtimeType == other.runtimeType &&
          id == other.id;

  @override
  int get hashCode => id.hashCode;
}
